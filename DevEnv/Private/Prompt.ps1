# Prompt component, in two parts:
#   Prompt config  generates each shell's prompt config from the manifest's Prompt section, next to the
#                  prompt scripts: powershell/dualline-prompt.config.psd1 and bash/dualline-prompt.config.sh
#   Prompt         adds a block to the PowerShell 7 'Current User, All Hosts' profile that loads
#                  powershell/dualline-prompt.ps1, using the VSCode segments inside the VS Code terminal
# (bash loads its config itself; the Wsl component adds it to ~/.bashrc.)

$script:PromptBlockHeader = '# Dual line prompt from dev-env-customization'
$script:PromptSegmentNames = 'os', 'path', 'git', 'docker', 'time', 'gap'
$script:PromptConfigPaths = @{
    PowerShell = Join-Path $script:RepoRoot 'powershell\dualline-prompt.config.psd1'
    Bash       = Join-Path $script:RepoRoot 'bash\dualline-prompt.config.sh'
}

# Throws if the manifest's Prompt section can't be turned into a working prompt
function Test-PromptConfig([Collections.IDictionary]$Prompt) {
    if (-not $Prompt -or -not $Prompt.Palette) { throw 'The manifest has no Prompt.Palette' }
    $palette = $Prompt.Palette
    foreach ($key in 'textlight', 'textdark', 'frame', 'chevron', 'error') {
        if (-not $palette[$key]) { throw "Prompt.Palette.$key is missing" }
    }
    foreach ($key in $palette.Keys) {
        if ($palette[$key] -notmatch '^#[0-9A-Fa-f]{6}$') { throw "Prompt.Palette.$key is '$($palette[$key])', not a #RRGGBB color" }
    }
    foreach ($list in 'Segments', 'VSCodeSegments') {
        $segments = @($Prompt[$list])
        if ($list -eq 'Segments' -and -not $segments) { throw 'Prompt.Segments is empty' }
        $unknown = @($segments | Where-Object { $_ -cnotin $script:PromptSegmentNames })
        if ($unknown) {
            throw "Unknown segment in Prompt.$list`: $($unknown -join ', ') (available: $($script:PromptSegmentNames -join ', '))"
        }
        if ($segments.Count -and -not $palette["section$($segments.Count - 1)"]) {
            throw "Prompt.$list has $($segments.Count) segments, so Prompt.Palette needs section0 to section$($segments.Count - 1)"
        }
    }
    if ([string]$Prompt.DirTruncationLength -notmatch '^[1-9][0-9]*$') { throw 'Prompt.DirTruncationLength must be a whole number of at least 1' }
    if (-not $Prompt.TimeFormat) { throw 'Prompt.TimeFormat is empty' }
}

# Converts a .NET time format like 'HH:mm' to the strftime format bash uses ('%H:%M')
function ConvertTo-StrftimeFormat([string]$Format) {
    [regex]::Replace($Format.Replace('%', '%%'), 'HH|H|hh|h|mm|m|ss|s|tt', {
            param($match)
            switch -CaseSensitive ($match.Value) {
                'HH' { '%H' } 'H' { '%-H' } 'hh' { '%I' } 'h' { '%-I' }
                'mm' { '%M' } 'm' { '%-M' } 'ss' { '%S' } 's' { '%-S' } 'tt' { '%p' }
            }
        })
}

# The generated config files: path -> content
function Get-PromptConfigFile([Collections.IDictionary]$Config) {
    $prompt = $Config.Prompt
    Test-PromptConfig $prompt
    $segments = @($prompt.Segments)
    $vscodeSegments = if ($prompt.VSCodeSegments) { @($prompt.VSCodeSegments) } else { $segments }
    $keys = $prompt.Palette.Keys | Sort-Object
    $width = ($keys | Measure-Object -Property Length -Maximum).Maximum
    $note = 'Generated by Sync-DevEnv from the Prompt section of the manifest. Edit your manifest instead: this file is overwritten.'

    $powershell = @(
        "# $note"
        '@{'
        '    Palette             = @{'
        foreach ($key in $keys) { "        $($key.PadRight($width)) = '$($prompt.Palette[$key])'" }
        '    }'
        "    Segments            = @($(($segments | ForEach-Object { "'$_'" }) -join ', '))"
        "    VSCodeSegments      = @($(($vscodeSegments | ForEach-Object { "'$_'" }) -join ', '))"
        "    DirTruncationLength = $([int]$prompt.DirTruncationLength)"
        "    TimeFormat          = '$(([string]$prompt.TimeFormat).Replace("'", "''"))'"
        '}'
    )
    $bash = @(
        "# $note"
        foreach ($key in $keys) { "_dl_palette[$key]='$($prompt.Palette[$key])'" }
        "_dl_segments=($($segments -join ' '))"
        "_dl_vscode_segments=($($vscodeSegments -join ' '))"
        "_dl_dir_truncation_length=$([int]$prompt.DirTruncationLength)"
        "_dl_time_format=$(ConvertTo-BashLiteral (ConvertTo-StrftimeFormat $prompt.TimeFormat))"
    )
    # LF line endings, since bash in WSL reads the file too
    [ordered]@{
        $script:PromptConfigPaths.PowerShell = ($powershell -join "`n") + "`n"
        $script:PromptConfigPaths.Bash       = ($bash -join "`n") + "`n"
    }
}

function Sync-PromptConfig {
    [CmdletBinding(SupportsShouldProcess)]
    param(
        [Parameter(Mandatory)]
        [Collections.IDictionary]$Config,
        [switch]$Check
    )
    $files = Get-PromptConfigFile $Config
    $stale = @($files.Keys | Where-Object { -not (Test-Path -LiteralPath $_) -or [IO.File]::ReadAllText($_) -cne $files[$_] })
    if (-not $stale) { return New-DevEnvResult 'Prompt config' UpToDate 'Palette and segments for PowerShell and bash' }
    $names = ($stale | ForEach-Object { Split-Path -Leaf $_ }) -join ', '
    if ($Check -or -not $PSCmdlet.ShouldProcess($names, 'Write prompt config')) {
        return New-DevEnvResult 'Prompt config' NeedsUpdate "$names missing or out of date"
    }
    foreach ($path in $stale) { [IO.File]::WriteAllText($path, $files[$path]) }
    New-DevEnvResult 'Prompt config' Updated "Wrote $names; open a new terminal to see the change"
}

function Remove-PromptConfig {
    [CmdletBinding(SupportsShouldProcess)]
    param()
    $existing = @($script:PromptConfigPaths.Values | Where-Object { Test-Path -LiteralPath $_ })
    if (-not $existing) { return New-DevEnvResult 'Prompt config' NotInstalled 'No generated prompt config' }
    $names = ($existing | ForEach-Object { Split-Path -Leaf $_ }) -join ', '
    if (-not $PSCmdlet.ShouldProcess($names, 'Delete prompt config')) { return New-DevEnvResult 'Prompt config' WouldRemove $names }
    Remove-Item -LiteralPath $existing
    New-DevEnvResult 'Prompt config' Removed $names
}

function Sync-PromptProfile {
    [CmdletBinding(SupportsShouldProcess)]
    param(
        [string]$ProfilePath = $PROFILE.CurrentUserAllHosts,
        [switch]$Check
    )
    if ((Test-Path -LiteralPath $ProfilePath) -and
        (Select-String -LiteralPath $ProfilePath -Pattern 'dualline-prompt\.ps1' -Quiet)) {
        return New-DevEnvResult Prompt UpToDate $ProfilePath
    }
    if ($Check -or -not $PSCmdlet.ShouldProcess($ProfilePath, 'Add the prompt to the profile')) {
        return New-DevEnvResult Prompt NeedsUpdate "$ProfilePath doesn't load the prompt"
    }

    # Write the path relative to $HOME when possible, so a profile synced to another machine (for example
    # through OneDrive) still works there
    $promptScript = Join-Path $script:RepoRoot 'powershell\dualline-prompt.ps1'
    $pathText = if ($promptScript.StartsWith("$HOME\", [StringComparison]::OrdinalIgnoreCase)) {
        '$HOME' + $promptScript.Substring($HOME.Length)
    }
    else { $promptScript }

    $block = @"

$script:PromptBlockHeader (added by DevEnv)
`$devEnvPrompt = "$pathText"
if (Test-Path -LiteralPath `$devEnvPrompt) {
    . `$devEnvPrompt -Variant `$(if (`$env:TERM_PROGRAM -eq 'vscode') { 'VSCode' } else { 'Default' })
}
Remove-Variable devEnvPrompt
"@

    New-Item -ItemType Directory -Force (Split-Path -Parent $ProfilePath) | Out-Null
    Add-Content -LiteralPath $ProfilePath -Value $block -Encoding utf8NoBOM
    New-DevEnvResult Prompt Updated $ProfilePath
}

# Removes the block Sync-PromptProfile added. A line loading the prompt that was added by hand is left alone.
function Remove-PromptProfile {
    [CmdletBinding(SupportsShouldProcess)]
    param(
        [string]$ProfilePath = $PROFILE.CurrentUserAllHosts
    )
    $text = if (Test-Path -LiteralPath $ProfilePath) { Get-Content -LiteralPath $ProfilePath -Raw }
    if (-not $text) { return New-DevEnvResult Prompt NotInstalled $ProfilePath }

    # From the header comment (and the blank line before it) to the closing Remove-Variable line
    $pattern = '(?ms)(\r?\n)?^' + [regex]::Escape($script:PromptBlockHeader) + '.*?^Remove-Variable devEnvPrompt[^\r\n]*(\r?\n)?'
    $newText = [regex]::Replace($text, $pattern, '')
    $byHand = 'loads the prompt with a line not added by DevEnv; remove it by hand'

    if ($newText -eq $text) {
        if ($text -match 'dualline-prompt\.ps1') { return New-DevEnvResult Prompt Skipped "$ProfilePath $byHand" }
        return New-DevEnvResult Prompt NotInstalled $ProfilePath
    }
    if (-not $PSCmdlet.ShouldProcess($ProfilePath, 'Remove the prompt from the profile')) {
        return New-DevEnvResult Prompt WouldRemove $ProfilePath
    }

    Copy-Item -LiteralPath $ProfilePath -Destination "$ProfilePath.bak" -Force
    Write-Verbose "Backed up $ProfilePath to $ProfilePath.bak"
    Write-FileWithRetry -Path $ProfilePath -Value $newText -NoNewline
    if ($newText -match 'dualline-prompt\.ps1') { Write-Warning "$ProfilePath still $byHand" }
    New-DevEnvResult Prompt Removed $ProfilePath
}

# The config goes first, so the profile loads a prompt that's already configured
function Sync-DevEnvPrompt {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [Collections.IDictionary]$Config,
        [string]$ProfilePath = $PROFILE.CurrentUserAllHosts,
        # Only report what would change
        [switch]$Check
    )
    Sync-PromptConfig -Config $Config -Check:$Check
    Sync-PromptProfile -ProfilePath $ProfilePath -Check:$Check
}

function Remove-DevEnvPrompt {
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSUseShouldProcessForStateChangingFunctions', '', Justification = 'Delegated to Remove-PromptProfile and Remove-PromptConfig, which call ShouldProcess')]
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSReviewUnusedParameter', '', Justification = 'Every component function takes -Config')]
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [Collections.IDictionary]$Config,
        [string]$ProfilePath = $PROFILE.CurrentUserAllHosts
    )
    Remove-PromptProfile -ProfilePath $ProfilePath
    Remove-PromptConfig
}
